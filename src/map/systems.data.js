/**
 * ══════════════════════════════════════════════════════════════════════════
 *  systems.data.js — ТВОЙ файл. Здесь ты описываешь системы кампании.
 *  Полный гайд: src/map/HOWTO.md
 * ══════════════════════════════════════════════════════════════════════════
 *
 * Пиши КОРОТКО — движок всё поймёт и дополнит сам:
 *
 *   {
 *     node: 512,                  // узел карты (номер из карточки узла
 *                                 //  или SWN.chart.dumpNodes()); можно
 *                                 //  'auto:center' / 'auto:edge'
 *     name: 'Моя система',        // имя — обязательно
 *     role: 'фронтир',            // строка под именем
 *     star: 'sun',                // 'sun' | 'blackhole' | 'dyson' | 'startut'
 *                                 // | цвет словом ('красный') или '#ffcc66'
 *     planets: [
 *       { name: 'Земля Новая', texture: 'Europa', size: 1.4 },
 *       { name: 'Фобос', color: 'красный', size: 0.6 },
 *     ],
 *   }
 *
 * Короткие поля планет:
 *   size      = radius (радиус в юнитах)
 *   texture   'Mars' → '/planets/textures/Mars.jpg'
 *             (доступны: Europa, Mars, Neptune, Pluto, Saturn, Venus)
 *   color     'красный' / '#ff6a4d' / 0xff6a4d — однотонная планета
 *   model     путь к .glb (например '/stars/models/blackhole.glb')
 *   orbit     радиус орбиты; не укажешь — расставим сами (30, 55, 80…)
 *   speed     скорость орбиты; по умолчанию 0.002 (движок ещё и
 *             замедляет всё в ~3 раза, чтобы вращение было спокойным)
 *   ring: true          — планета с кольцами
 *   offset: [x, y, z]   — статичный объект вместо орбиты
 *   kind, tag, pop, tech, tags — текст для карточки
 *
 * Необязательное можно не писать вообще: минимальная запись —
 *   { node: 512, name: 'Моя система' }
 *
 * Быстрая проверка без перезагрузки — в консоли браузера:
 *   SWN.chart.addSystem({ node: 512, name: 'Тест', star: 'sun' })
 * ══════════════════════════════════════════════════════════════════════════
 */

